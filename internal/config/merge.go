package config

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"

	"github.com/tailscale/hujson"
)

// GeneratedHeader marks opencode.jsonc as written by rutter.
const GeneratedHeader = "// Generated by rutter. Edit config/opencode.base.json or opencode.personal.json instead.\n"

// ErrInvalid reports a config document rutter cannot parse.
var ErrInvalid = errors.New("invalid config")

// CombineKeys are arrays that append when the personal config overrides the
// team base. Every other array replaces the base value.
var CombineKeys = map[string]bool{
	"permissions":  true,
	"instructions": true,
	"skills":       true,
	"plugins":      true,
}

// Merger joins the team base config with the machine-local personal config.
type Merger struct{}

// MergeFiles reads both JSONC files and returns the merged document.
func (Merger) MergeFiles(basePath, personalPath string) ([]byte, error) {
	base, err := os.ReadFile(basePath)
	if err != nil {
		return nil, fmt.Errorf("read base config: %w", err)
	}

	personal := []byte("{}")
	if personalPath != "" {
		body, readErr := os.ReadFile(personalPath)
		switch {
		case readErr == nil:
			personal = body
		case errors.Is(readErr, os.ErrNotExist):
		default:
			return nil, fmt.Errorf("read personal config: %w", readErr)
		}
	}

	return Merger{}.Merge(base, personal)
}

// Merge returns the merged document with a generated-file header.
func (Merger) Merge(base, personal []byte) ([]byte, error) {
	baseMap, err := decodeObject(base, "base")
	if err != nil {
		return nil, err
	}
	personalMap, err := decodeObject(personal, "personal")
	if err != nil {
		return nil, err
	}

	merged := mergeValue(baseMap, personalMap, "")
	out, err := json.MarshalIndent(merged, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode merged config: %w", err)
	}

	return append([]byte(GeneratedHeader), append(out, '\n')...), nil
}

func decodeObject(raw []byte, label string) (map[string]any, error) {
	if len(bytes.TrimSpace(raw)) == 0 {
		return map[string]any{}, nil
	}

	standard, err := hujson.Standardize(raw)
	if err != nil {
		return nil, fmt.Errorf("%w: parse %s config: %w", ErrInvalid, label, err)
	}

	var value map[string]any
	decoder := json.NewDecoder(bytes.NewReader(standard))
	decoder.UseNumber()
	if err := decoder.Decode(&value); err != nil {
		return nil, fmt.Errorf("%w: decode %s config: %w", ErrInvalid, label, err)
	}
	if value == nil {
		value = map[string]any{}
	}
	return value, nil
}

func mergeValue(base, override any, key string) any {
	if override == nil {
		return nil
	}

	baseMap, baseIsMap := base.(map[string]any)
	overrideMap, overrideIsMap := override.(map[string]any)
	if baseIsMap && overrideIsMap {
		merged := make(map[string]any, len(baseMap)+len(overrideMap))
		for k, v := range baseMap {
			merged[k] = v
		}
		for k, v := range overrideMap {
			merged[k] = mergeValue(baseMap[k], v, k)
		}
		return merged
	}

	baseSlice, baseIsSlice := base.([]any)
	overrideSlice, overrideIsSlice := override.([]any)
	if baseIsSlice && overrideIsSlice {
		if CombineKeys[key] {
			merged := make([]any, 0, len(baseSlice)+len(overrideSlice))
			merged = append(merged, baseSlice...)
			merged = append(merged, overrideSlice...)
			return merged
		}
		return overrideSlice
	}

	return override
}
